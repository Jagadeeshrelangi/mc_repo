def test_diagnosis_history_and_detail_flow(test_app: FastAPI, monkeypatch) -> None:
    token_a = security.create_access_token(USER_A_ID)
    client = TestClient(test_app)

    # 1. Mock service list_user_diagnoses
    from app.services.diagnosis_service import diagnosis_service
    dummy_records = [
        Diagnosis(
            id="diag-1",
            user_id=USER_A_ID,
            problem="Overheating Engine",
            symptoms={"items": ["steam"]},
            severity="high",
            estimated_cost=2500.0,
            recommended_action="Stop immediately.",
            should_drive=False,
            confidence=95,
            vehicle_name="Honda City",
            vehicle_type="Car",
            created_at=NOW,
        )
    ]

    async def mock_list(session, user_id, offset=0, limit=50):
        if user_id == USER_A_ID:
            return dummy_records
        return []

    async def mock_get(session, diagnosis_id, user_id):
        if user_id == USER_A_ID and diagnosis_id == "diag-1":
            return dummy_records[0]
        return None

    async def mock_delete(session, diagnosis_id, user_id):
        if user_id == USER_A_ID and diagnosis_id == "diag-1":
            return True
        return False

    monkeypatch.setattr(diagnosis_service, "list_user_diagnoses", mock_list)
    monkeypatch.setattr(diagnosis_service, "get_user_diagnosis", mock_get)
    monkeypatch.setattr(diagnosis_service, "delete_user_diagnosis", mock_delete)

    # 2. Get history as User A
    res = client.get(
        "/api/v1/diagnosis/history",
        headers={"Authorization": f"Bearer {token_a}"},
    )
    assert res.status_code == status.HTTP_200_OK
    data = res.json()
    assert len(data) == 1
    assert data[0]["id"] == "diag-1"
    assert data[0]["problem"] == "Overheating Engine"
    assert data[0]["confidence"] == 95

    # 3. Get detail of diag-1 as User A (200 OK)
    res = client.get(
        "/api/v1/diagnosis/diag-1",
        headers={"Authorization": f"Bearer {token_a}"},
    )
    assert res.status_code == status.HTTP_200_OK
    detail = res.json()
    assert detail["id"] == "diag-1"
    assert detail["estimated_cost"] == 2500.0

    # 4. User B attempts to get diag-1 (returns 404 NOT_FOUND due to ownership)
    token_b = security.create_access_token(USER_B_ID)
    res_b = client.get(
        "/api/v1/diagnosis/diag-1",
        headers={"Authorization": f"Bearer {token_b}"},
    )
    assert res_b.status_code == status.HTTP_404_NOT_FOUND

    # 5. User B attempts to delete diag-1 (returns 404 NOT_FOUND)
    res_del_b = client.delete(
        "/api/v1/diagnosis/diag-1",
        headers={"Authorization": f"Bearer {token_b}"},
    )
    assert res_del_b.status_code == status.HTTP_404_NOT_FOUND

    # 6. User A deletes diag-1 (returns 204 NO_CONTENT)
    res_del_a = client.delete(
        "/api/v1/diagnosis/diag-1",
        headers={"Authorization": f"Bearer {token_a}"},
    )
    assert res_del_a.status_code == status.HTTP_204_NO_CONTENT
    assert test_app.state.last_session.committed is True
