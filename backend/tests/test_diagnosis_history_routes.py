@pytest.mark.anyio
async def test_diagnosis_repository_ownership_isolation() -> None:
    from app.repositories.diagnosis import DiagnosisRepository
    from unittest.mock import AsyncMock, MagicMock

    session = AsyncMock()
    repo = DiagnosisRepository(session)

    # When query executes for user_id = USER_A_ID and diagnosis_id = diag-bbbb00000001
    mock_result = MagicMock()
    mock_result.one_or_none.return_value = None
    session.scalars.return_value = mock_result

    # Should return None when user A tries to access user B's diagnosis
    res = await repo.get_diagnosis_by_id("diag-bbbb00000001", USER_A_ID)
    assert res is None

    # Deleting unauthorized diagnosis should return False
    del_res = await repo.delete_diagnosis("diag-bbbb00000001", USER_A_ID)
    assert del_res is False


