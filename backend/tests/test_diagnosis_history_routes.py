@pytest.fixture
def test_app(fake_db: FakeDiagnosisDatabase, monkeypatch) -> FastAPI:
    monkeypatch.setattr(settings, "JWT_SECRET_KEY", "diag-history-test-secret")

    from fastapi.responses import JSONResponse
    from app.core.exceptions import MechaException

    app = FastAPI()

    @app.exception_handler(MechaException)
    async def mecha_exception_handler(request, exc: MechaException):
        status_code = status.HTTP_500_INTERNAL_SERVER_ERROR
        if exc.code == "NOT_FOUND":
            status_code = status.HTTP_404_NOT_FOUND
        elif exc.code == "UNAUTHORIZED":
            status_code = status.HTTP_401_UNAUTHORIZED
        elif exc.code == "BAD_REQUEST":
            status_code = status.HTTP_400_BAD_REQUEST
        elif exc.code == "INFERENCE_FAILED":
            status_code = status.HTTP_422_UNPROCESSABLE_ENTITY

        return JSONResponse(
            status_code=status_code,
            content={"error_code": exc.code, "message": exc.message, "details": exc.details},
        )

    app.include_router(diagnosis_router, prefix="/api/v1/diagnosis")

    async def override_get_db():
        session = FakeDiagnosisSession(fake_db)
        app.state.last_session = session
        yield session

    app.dependency_overrides[get_db] = override_get_db
    return app


